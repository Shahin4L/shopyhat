assert(resellerHTML.includes('id="successLogin"'),'Missing return to reseller login');
assert(resellerHTML.includes('id="selfPasswordForm"'),'Missing reseller password update');
assert(reseller.includes("form.reset();$('applyPanel').hidden"),'Reseller signup form is not reset safely after awaiting');
assert(!reseller.includes('event.currentTarget.reset()'),'Unsafe async event.currentTarget reset remains');
assert(reseller.includes("db.auth.updateUser({password:pass})"),'Reseller password update missing');
assert(admin.includes("credentialRequest('create'"),'Admin create credentials missing');
assert(admin.includes("credentialRequest('reset'"),'Admin password reset missing');
assert(!admin.includes('name="user_id"'),'Admin should not require Supabase UUID');
assert(edge.includes('auth.admin.createUser'),'Credential creation must run on server');
assert(edge.includes('auth.admin.updateUserById'),'Credential reset must run on server');
assert(edge.includes("['owner','manager'].includes(staff.role)"),'Admin role validation missing');
assert(studio.includes('id="shExperiencePreviewFrame"'),'Visual preview iframe missing');
assert(studio.includes('function previewConfig()'),'Unsaved design preview missing');
assert(storefront.includes("event.origin!==location.origin"),'Preview origin enforcement missing');
assert(storefront.includes("event.source!==window.parent"),'Preview sender enforcement missing');
assert(storefront.includes("main.querySelector('a[data-p=\"saree\"]')"),'New Arrivals placement missing');
assert(home.includes('pg==="arrivals"?"home"'),'New Arrivals route missing');
assert(adminHTML.includes('id="orderPaymentFilter"'),'Order payment method filter missing');
assert(adminHTML.includes('id="orderPaymentState"'),'Order payment status filter missing');
assert(workflow.includes("await cp('reseller'"),'Production build omits reseller portal');
new Function(reseller.replace(/^import .*?;\s*$/gm,''));
new Function(admin.replace(/^import[^\n]*\n/gm,'').replace(/^export /gm,''));

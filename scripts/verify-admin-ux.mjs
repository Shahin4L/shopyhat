import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
const text=path=>readFileSync(path,'utf8');
const reseller=text('reseller/app.js'),resellerHTML=text('reseller/index.html');
const admin=text('admin/resellers.js'),adminHTML=text('admin/index.html');
const studio=text('admin/experience.js'),storefront=text('storefront-experience.js');
const home=text('index.html'),edge=text('supabase/functions/shopyhat-reseller-access/index.ts');
const workflow=text('scripts/build.mjs');

import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';

const read=p=>readFileSync(p,'utf8');
const html=read('index.html'),account=read('customer-account.js'),css=read('customer-account.css');
const admin=read('admin/app.js'),resellers=read('admin/resellers.js');
const partner=read('reseller/app.js'),partnerHTML=read('reseller/index.html');
const checkout=read('supabase/functions/shopyhat-checkout/index.ts');
const build=read('scripts/build.mjs'),reset=read('reset-password.html'),confirm=read('account-confirmed.html');
new Function(account.replace(/^import .*?;\s*$/gm,''));
new Function(partner.replace(/^import .*?;\s*$/gm,''));
new Function(resellers.replace(/^import[^\n]*\n/gm,'').replace(/^export /gm,''));
assert(html.includes('customer-account.js'),'Customer account missing from storefront');
assert(html.includes('customer-account.css'),'Customer styles missing');
assert(account.includes("storageKey:'sh_customer_auth_v1'"),'Customer Auth must use separate session');
assert(account.includes('db.auth.signUp({email,'),'Email/password customer signup missing');
assert(!account.includes('db.auth.verifyOtp({phone:'),'SMS OTP must not be present in customer flow');
assert(account.includes("db.auth.resetPasswordForEmail("),'Email recovery missing');
assert(reset.includes('db.auth.updateUser({password:a})'),'Secure reset page missing');
assert(confirm.includes('email_confirmed_at'),'Optional confirmation callback page missing');
assert(account.includes('authIntro(')&&account.includes('sh-auth-nav'),'Premium login/register tabs missing');
assert(account.includes('data-toggle-password'),'Password visibility toggle missing');
assert(account.includes('Continue as guest'),'Guest account escape missing');
assert(!account.includes('if(!data.user?.email_confirmed_at)'),'Customer login must not require email confirmation');
assert(!account.includes('signedUser=user?.email_confirmed_at?user:null'),'Account ownership must use valid session rather than email-confirmed flag');
assert(checkout.includes("app_metadata?.account_type!=='reseller'"),'Checkout must exclude reseller sessions');
assert(!checkout.includes('verified.data.user?.email_confirmed_at'),'Checkout should not require email-confirmed users');
assert(account.includes("db.rpc('sh_customer_orders')"),'Authenticated customer order history missing');
assert(account.includes('sh_customer_watches'),'Cart/wishlist stock alerts missing');
assert(account.includes("db.from('sh_customer_notifications')"),'Notification inbox missing');
assert(partner.includes('sh_apply_reseller'),'Reseller application missing');
assert(partner.includes("storageKey:'sh_reseller_auth_v1'"),'Reseller auth session not isolated');
assert(partner.includes('sh_reseller_request'),'Reseller fulfillment request missing');
assert(partner.includes('shop_slug'),'Named reseller link missing');
assert(partner.includes('db.auth.updateUser({password:pass})'),'Forced temporary password change missing');
assert(partnerHTML.includes('Reseller Login'),'Dedicated login page missing');
assert(html.includes('referrer_slug:'),'Named reseller attribution missing at checkout');
assert(checkout.includes('approvedReferrer'),'Referral server validation missing');
assert(checkout.includes('signedCustomerId'),'Authenticated account order ownership missing');
assert(admin.includes('resellers.mount()'),'Reseller Admin module not wired');
assert(resellers.includes('sh_reseller_applications'),'Admin application review missing');
assert(resellers.includes('sh_reseller_referrals'),'Admin referral settlement missing');
assert(css.includes('@media(max-width:650px)'),'Responsive customer panel missing');
assert(build.includes("await cp('reseller'"),'Reseller portal not copied to production build');
assert(build.includes('reset-password.html'),'Password reset page missing from build');
console.log('SHOPYHAT email/password customer and reseller integration checks passed.');

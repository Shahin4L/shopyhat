import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>readFileSync(p,'utf8');
const home=read('index.html'),admin=read('admin/app.js'),care=read('customer-care.js'),reseller=read('admin/resellers.js');
const tracker=read('supabase/functions/shopyhat-track-order/index.ts');
new Function(admin.replace(/^import[^\n]*\n/gm,'').replace(/^export /gm,''));
new Function(reseller.replace(/^import[^\n]*\n/gm,'').replace(/^export /gm,''));
new Function(care);
const jsTags=[...home.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)]
 .filter(([,attrs,src])=>!/(?:type\s*=\s*["']application\/ld\+json|\bsrc\s*=)/i.test(attrs)&&src.trim());
for(const [,attrs,src] of jsTags)new Function(src);
assert(home.includes('SH_TRACK_URL'), 'Server tracking endpoint missing');
assert(home.includes('fetch(SH_TRACK_URL'), 'Cross-device tracking must call server');
assert(!home.includes('if(SHEET){try{const r=await fetch(SHEET+"?action=track'), 'Legacy local-only tracking should be replaced');
assert(home.includes('const loggedProfile=window.SHOPYHAT_CUSTOMER?.getUser?.()?'), 'Account checkout prefill must work without phone OTP');
assert(!home.includes('getUser?.()?.phone_confirmed_at?'), 'No phone OTP should be required for checkout prefill');
assert(home.includes('if(token&&window.SHOPYHAT_CUSTOMER?.getUser?.())'), 'Existing authenticated accounts must own their new orders');
assert(!home.includes('if(token&&window.SHOPYHAT_CUSTOMER?.getUser?.()?.email_confirmed_at)'), 'No signup email confirmation should be added');
assert(admin.includes("'collected - cod'"), 'Verified COD collection must be reported');
assert(!admin.includes("toLowerCase().includes('paid')"), 'Revenue must never treat Unpaid as Paid');
assert(admin.includes('Confirm COD Collection'), 'COD settlement confirmation action missing');
assert(admin.includes("for(let offset=0;offset<limit;offset+=batch)"), 'Admin pagination missing');
assert(reseller.includes("fetchSection('sh_reseller_referrals')"), 'Reseller rows must not silently truncate');
assert(care.includes('prefillAccount({csName:'), 'Customer case account prefill missing');
assert(care.includes('prefillAccount({rvName:'), 'Customer reviews account prefill missing');
assert(tracker.includes("sh_track_order_rpc")&&tracker.includes("fingerprint("), 'Restricted rate-limited tracking backend missing');
assert(home.includes('rel="canonical"'), 'Canonical SEO URL missing');
assert(read('robots.txt').includes('Sitemap:')&&read('sitemap.xml').includes('<urlset'), 'Basic SEO crawl files missing');
const paid = status=>['verified - paid','verified','paid','payment received','collected - cod'].includes(String(status??'').trim().toLowerCase());
for(const s of ['Unpaid - COD','Pending Verification','Refund Pending','Rejected','Refunded'])assert(!paid(s),s+' should not be counted as paid');
for(const s of ['Verified - Paid','Collected - COD'])assert(paid(s),s+' should count as verified receipt');
console.log('SHOPYHAT Phase 0–4 static regression, payout status and frontend script parsing PASS.');
